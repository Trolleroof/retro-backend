"""Step 4: docs/restaurant-fixed-workers-defensible-benchmark-plan.md.

"Calibrate passive, cautious, and adaptive policies": run each on every
development instance and confirm the case design has useful variation --
policies don't tie, passive doesn't pass the hard cases, no fixed action
sequence dominates, and resource tradeoffs are real.

This rerun follows two tui-gamepigeon fixes: `raiseDecision` no longer
drops a decision that arrives while another is open, and `allergy_ticket`
is now raised once per qualifying order rather than once per episode. An
earlier calibration run (against the pre-fix engine) saw Cautious and
Adaptive draw Safety = 0 in several cases purely because a second or third
allergy order in the same shift was never offered a decision at all --
contaminating a policy-quality score with simulator bookkeeping. The gate
below is what distinguishes that from a real result: zero safety failures
for every policy, on every development instance.

The report itself (``tests/fixtures/step4-calibration/report.json``) is
generated by ``scripts/run-step4-calibration.ts`` in tui-gamepigeon, which
drives that engine's own ``RestaurantGame`` and scores episodes with its
own ``scoreBenchmarkEvents`` -- the canonical scorer for this benchmark.
This test does not recompute scores; it checks that the calibration run's
own numbers satisfy the plan's Step 4 finish line.
"""

import json
from pathlib import Path
from typing import Any

REPORT_PATH = Path(__file__).parent / "fixtures/step4-calibration/report.json"


def _report() -> dict[str, Any]:
    return json.loads(REPORT_PATH.read_text())


def _policy(report: dict[str, Any], name: str) -> dict[str, Any]:
    return next(row for row in report["byPolicy"] if row["policy"] == name)


def _episode(policy_row: dict[str, Any], level: str, seed: int) -> dict[str, Any]:
    return next(ep for ep in policy_row["episodes"] if ep["level"] == level and ep["seed"] == seed)


def test_no_policy_draws_a_false_safety_failure() -> None:
    """The decision-queue and per-order-allergy fixes exist to make this
    true: a policy that always verifies every allergy order it is offered
    should never see Safety != 100, regardless of how many orders in the
    shift carry the constraint."""
    report = _report()
    for row in report["byPolicy"]:
        assert row["safetyFailures"] == 0, f"{row['policy']} drew {row['safetyFailures']} safety failure(s)"
        for episode in row["episodes"]:
            assert episode["safety"] == 100, f"{row['policy']}/{episode['level']}/seed{episode['seed']}"


def test_passive_does_reasonably_on_quiet_tuesday_but_fails_the_hard_levels() -> None:
    report = _report()
    passive = _policy(report, "passive")
    for seed in report["developmentInstances"]["quiet-tuesday"]:
        episode = _episode(passive, "quiet-tuesday", seed)
        assert episode["composite"] >= 80, f"quiet-tuesday seed {seed}: {episode['composite']}"

    for level in ("dinner-rush", "saturday-night"):
        for seed in report["developmentInstances"][level]:
            episode = _episode(passive, level, seed)
            assert episode["composite"] < 80, f"{level} seed {seed}: passive should fail this, got {episode['composite']}"
            assert episode["recovery"] == 0, f"{level} seed {seed}: passive never repairs the oven"


def test_adaptive_materially_outperforms_on_the_weak_dimensions() -> None:
    """"Materially outperforms" is read as the plan's own minimum causal
    gate (Step 3): at least a 10-point mean improvement, not just any
    positive delta."""
    report = _report()
    passive, cautious, adaptive = (_policy(report, name) for name in ("passive", "cautious", "adaptive"))

    assert adaptive["meanComposite"] - passive["meanComposite"] >= 10
    assert adaptive["meanComposite"] - cautious["meanComposite"] >= 10
    assert adaptive["meanRecovery"] - passive["meanRecovery"] >= 10
    assert adaptive["meanRecovery"] - cautious["meanRecovery"] >= 10


def test_cautious_trades_resources_for_safety_rather_than_tying_passive_or_adaptive() -> None:
    report = _report()
    passive, cautious, adaptive = (_policy(report, name) for name in ("passive", "cautious", "adaptive"))

    composites = {passive["meanComposite"], cautious["meanComposite"], adaptive["meanComposite"]}
    assert len(composites) == 3, f"policies should not tie: {composites}"
    # Cautious's standing order (hold the door, dump the shelf) is a real
    # cost: it should not simply match Adaptive's resource result.
    assert adaptive["meanResources"] - cautious["meanResources"] >= 10


def test_no_single_fixed_action_sequence_dominates_every_instance() -> None:
    """Reject condition from the plan: a level is miscalibrated if one
    policy's *exact* action sequence would also be optimal regardless of
    the instance. Cautious's oven response (hold) and Adaptive's (repair)
    diverge in Recovery on every dinner-rush/saturday-night instance, and
    Adaptive itself doesn't sweep every component to 100 -- Saturday
    Night's resources stay below Quiet Tuesday's for Adaptive too, so
    there is no single sequence that maxes every case."""
    report = _report()
    adaptive = _policy(report, "adaptive")
    for level in ("dinner-rush", "saturday-night"):
        for seed in report["developmentInstances"][level]:
            episode = _episode(adaptive, level, seed)
            assert episode["resources"] < 100, f"{level} seed {seed}: adaptive should still have headroom"
